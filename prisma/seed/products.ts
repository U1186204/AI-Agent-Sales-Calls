export interface SeedProduct {
  sku: string;
  name: string;
  category: string;
  description: string;
  priceCents: number;
  unit: string;
  weightLb: number;
  qtyOnHand: number;
}

type Row = [
  sku: string,
  name: string,
  category: string,
  description: string,
  priceCents: number,
  unit: string,
  weightLb: number,
  qty: number,
];

const toProducts = (rows: Row[]): SeedProduct[] =>
  rows.map(([sku, name, category, description, priceCents, unit, weightLb, qtyOnHand]) => ({
    sku,
    name,
    category,
    description,
    priceCents,
    unit,
    weightLb,
    qtyOnHand,
  }));

